import { type Tree, visitNotIgnoredFiles } from '@nx/devkit';
import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** Marks a folder as an OpenStuff marketing site, and holds what its toolkit copy is built from. */
export const SITE_CONFIG = 'openstuff-site.json';

/** Where a site keeps its copy of the toolkit. Generated: `sync` rewrites it. */
export const VENDOR_DIR = 'assets/os';

export interface SiteConfig {
  /** The project's primary colour, as hex. The whole theme is generated from it. */
  primaryColor: string;
}

/** Geist and Geist Mono (SIL OFL), served by the site itself. */
const FONTS_DIR = join(__dirname, '..', 'files', 'site-fonts');

const FONT_FACES = `@font-face {
  font-family: 'Geist Variable';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('fonts/Geist-Variable.woff2') format('woff2');
}

@font-face {
  font-family: 'Geist Mono Variable';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('fonts/GeistMono-Variable.woff2') format('woff2');
}`;

function packageDir(name: string): string {
  return dirname(require.resolve(`${name}/package.json`));
}

function packageVersion(dir: string): string {
  return (JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string })
    .version;
}

/** Inlines `@import './x.css';` lines, so the browser loads one file instead of a waterfall. */
export function inlineImports(file: string): string {
  return readFileSync(file, 'utf8').replace(
    /^@import '(\.[^']+)';$/gm,
    (_line, path: string) => inlineImports(join(dirname(file), path)),
  );
}

/** The theme for one colour, in the os.tokens layer, the way os-tokens writes tokens.css. */
export async function tokensCss(primaryColor: string): Promise<string> {
  const { cssProperties, generateTheme } = await import('@openstuff-dev/tokens');
  const properties = Object.entries(cssProperties(generateTheme(primaryColor)))
    .map(([name, value]) => `    ${name}: ${value};`)
    .join('\n');
  return `@layer os.tokens {
  :root {
    color-scheme: light dark;
${properties}
  }

  :root[data-theme='light'] {
    color-scheme: light;
  }

  :root[data-theme='dark'] {
    color-scheme: dark;
  }
}`;
}

/**
 * Writes the site's copy of the toolkit into `<root>/assets/os`: `toolkit.css` (ui.css,
 * marketing.css, the fonts and the theme in one file), `marketing.js` and the fonts.
 * Static hosts like GitHub Pages serve it as it is, without a build step.
 */
export async function writeSiteToolkit(
  tree: Tree,
  root: string,
  config: SiteConfig,
): Promise<void> {
  const ui = packageDir('@openstuff-dev/ui');
  const header = [
    `/* Generated by @openstuff-dev/nx from @openstuff-dev/ui ${packageVersion(ui)} and`,
    ` * primaryColor ${config.primaryColor}. Don't edit: run npx nx g @openstuff-dev/nx:sync. */`,
    '/* stylelint-disable -- generated file */',
  ].join('\n');
  const css = [
    header,
    inlineImports(join(ui, 'css', 'ui.css')),
    readFileSync(join(ui, 'css', 'marketing.css'), 'utf8'),
    FONT_FACES,
    await tokensCss(config.primaryColor),
  ].join('\n\n');

  const vendor = `${root}/${VENDOR_DIR}`;
  tree.write(`${vendor}/toolkit.css`, `${css}\n`);
  tree.write(`${vendor}/marketing.js`, readFileSync(join(ui, 'dist', 'marketing.js')));
  for (const font of readdirSync(FONTS_DIR)) {
    tree.write(`${vendor}/fonts/${font}`, readFileSync(join(FONTS_DIR, font)));
  }
}

/** Every marketing site in the workspace: the folders with an openstuff-site.json. */
export function findSites(tree: Tree): string[] {
  const sites: string[] = [];
  visitNotIgnoredFiles(tree, '', (path) => {
    if (path === SITE_CONFIG || path.endsWith(`/${SITE_CONFIG}`)) {
      sites.push(dirname(path));
    }
  });
  return sites.sort();
}

/** Refreshes the toolkit copy of every site, e.g. after the ui package was upgraded. */
export async function syncSites(tree: Tree): Promise<string[]> {
  const sites = findSites(tree);
  for (const root of sites) {
    const config = JSON.parse(tree.read(`${root}/${SITE_CONFIG}`, 'utf8') ?? '{}') as SiteConfig;
    await writeSiteToolkit(tree, root, config);
  }
  return sites;
}
