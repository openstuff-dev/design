import StyleDictionary from 'style-dictionary';
import type { Format, Transform, TransformedToken } from 'style-dictionary/types';
import { lightDark, PREFIX } from '../lib/css.js';
import { DARK_EXTENSION, toDesignTokens, type DesignTokenGroup } from '../lib/design-tokens.js';
import type { Theme } from '../lib/theme.js';

interface ShadowValue {
  color: string;
  offsetX: string;
  offsetY: string;
  blur: string;
  spread: string;
}

function dark(token: TransformedToken): unknown {
  const extensions = token.$extensions as Record<string, unknown> | undefined;
  const value = extensions?.[DARK_EXTENSION];
  if (value === undefined) {
    throw new Error(`Token ${token.path.join('.')} has no dark value (${DARK_EXTENSION}).`);
  }
  return value;
}

const transforms: Transform[] = [
  {
    name: 'os/name',
    type: 'name',
    transform: (token, platform) => [platform.prefix, ...token.path].filter(Boolean).join('-'),
  },
  {
    name: 'os/color/light-dark',
    type: 'value',
    filter: (token) => token.$type === 'color',
    transform: (token) => lightDark({ light: token.$value as string, dark: dark(token) as string }),
  },
  {
    name: 'os/shadow/css',
    type: 'value',
    filter: (token) => token.$type === 'shadow',
    transform: (token) => {
      const darkColors = dark(token) as string[];
      return (token.$value as ShadowValue[])
        .map(({ color, offsetX, offsetY, blur, spread }, i) => {
          const pair = lightDark({ light: color, dark: darkColors[i] });
          return `${offsetX} ${offsetY} ${blur} ${spread} ${pair}`;
        })
        .join(', ');
    },
  },
];

const LIGHT_DARK = /^light-dark\(\s*[^,]+,\s*[^,]+\)$/;
const LIGHT_DARK_ANYWHERE = /light-dark\(\s*[^,]+,\s*[^,]+\)/g;

/**
 * Fails the build when a colour isn't a `light-dark()` pair, or a shadow has a colour
 * outside one, so a single-scheme colour can't slip into the output.
 */
export function assertLightDark(tokens: readonly TransformedToken[]): void {
  const wrong = tokens.filter((token) => {
    const value = String(token.$value);
    if (token.$type === 'color') return !LIGHT_DARK.test(value);
    if (token.$type === 'shadow') {
      const outsidePairs = value.replace(LIGHT_DARK_ANYWHERE, '');
      return !value.includes('light-dark(') || /oklch|rgb|hsl|lab|lch|color|#/.test(outsidePairs);
    }
    return false;
  });
  if (wrong.length > 0) {
    const names = wrong.map((token) => `  ${token.name}: ${String(token.$value)}`).join('\n');
    throw new Error(`Every colour token must be a light-dark() pair. These aren't:\n${names}`);
  }
}

const header = (theme: Theme) =>
  `Generated by @openstuff-dev/tokens from primaryColor ${theme.primary}. Don't edit by hand.`;

const formats: Format[] = [
  {
    name: 'os/css',
    format: ({ dictionary, options }) => {
      assertLightDark(dictionary.allTokens);
      const theme = options.theme as Theme;
      const lines = dictionary.allTokens.map((token) => `  --${token.name}: ${String(token.$value)};`);
      return [
        `/* ${header(theme)} */`,
        '/* stylelint-disable -- generated file */',
        ':root {',
        '  color-scheme: light dark;',
        ...lines,
        '}',
        '',
        '/* A person\'s choice overrides the system. */',
        ':root[data-theme=\'light\'] {',
        '  color-scheme: light;',
        '}',
        '',
        ':root[data-theme=\'dark\'] {',
        '  color-scheme: dark;',
        '}',
        '',
      ].join('\n');
    },
  },
  {
    name: 'os/javascript',
    format: ({ dictionary, options }) => {
      const theme = options.theme as Theme;
      const properties = Object.fromEntries(
        dictionary.allTokens.map((token) => [`--${token.name}`, token.$value]),
      );
      return [
        `// ${header(theme)}`,
        `export const theme = ${JSON.stringify(theme, null, 2)};`,
        '',
        `export const properties = ${JSON.stringify(properties, null, 2)};`,
        '',
      ].join('\n');
    },
  },
  {
    name: 'os/typescript',
    format: ({ dictionary, options }) => {
      const theme = options.theme as Theme;
      const names = dictionary.allTokens.map((token) => `  readonly '--${token.name}': string;`);
      return [
        `// ${header(theme)}`,
        'import type { Theme } from \'./index.js\';',
        '',
        '/** The theme these files were built from. */',
        'export declare const theme: Theme;',
        '',
        '/** Every custom property in tokens.css with its value. */',
        'export declare const properties: {',
        ...names,
        '};',
        '',
        'export type TokenName = keyof typeof properties;',
        '',
      ].join('\n');
    },
  },
  {
    name: 'os/dtcg',
    format: ({ options }) => `${JSON.stringify(options.tree, null, 2)}\n`,
  },
];

export const FILES = ['tokens.css', 'tokens.js', 'tokens.d.ts', 'tokens.json'] as const;

/** Writes tokens.css, tokens.js, tokens.d.ts and tokens.json (DTCG) for a theme into `outDir`. */
export async function buildWithStyleDictionary(theme: Theme, outDir: string): Promise<void> {
  const tree: DesignTokenGroup = toDesignTokens(theme);
  const buildPath = outDir.endsWith('/') ? outDir : `${outDir}/`;
  const sd = new StyleDictionary({
    tokens: tree,
    usesDtcg: true,
    log: { verbosity: 'silent' },
    hooks: {
      transforms: Object.fromEntries(transforms.map((t) => [t.name, t])),
      formats: Object.fromEntries(formats.map((f) => [f.name, f.format])),
    },
    platforms: {
      web: {
        prefix: PREFIX,
        buildPath,
        transforms: transforms.map((t) => t.name),
        options: { theme },
        files: [
          { destination: 'tokens.css', format: 'os/css' },
          { destination: 'tokens.js', format: 'os/javascript' },
          { destination: 'tokens.d.ts', format: 'os/typescript' },
        ],
      },
      dtcg: {
        buildPath,
        transforms: ['os/name'],
        options: { theme, tree },
        files: [{ destination: 'tokens.json', format: 'os/dtcg' }],
      },
    },
  });
  await sd.buildAllPlatforms();
}
